/** All questions indexed by their stable ID, for O(1) lookup. */
const QUESTION_BY_ID: Record<string, Question> = Object.fromEntries(
  Object.values(QUESTIONS)
    .flat()
    .map((q) => [q.id, q]),
);

/** Looks up a question by its stable ID. Throws if the ID is unknown. */
export function getQuestionById(id: string): Question {
  const question = QUESTION_BY_ID[id];
  if (!question) throw new Error(`Unknown question id: ${id}`);
  return question;
}
