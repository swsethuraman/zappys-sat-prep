// Zappy's SAT Prep — question bank, ported from the HTML prototype.
//
// Diagnostic vs. pool is distinguished by the explicit `diagnostic` flag on
// every Question — never by array position. Each concept exposes a single
// flat array mixing both sets; the diagnostic queue and practice-session
// builder derive their sets by *filtering* on `diagnostic`.
//
// Stable IDs follow `{concept}-d{n}` for diagnostic questions and
// `{concept}-p{n}` for pool questions (assigned in array order per concept).
// These IDs are the key for seen-question tracking, so they must never be
// renumbered once assigned.
//
// `misconceptionByChoice` is index-aligned with `choices`; the entry at
// `correctIndex` is an empty string and unused (the correct-answer
// feedback uses `explanation` instead). This mirrors OPACC-style
// pre-computed misconception feedback — no live LLM call needed.

import type { ConceptId } from './concepts';

export interface Question {
  /** Stable, unique ID: `{concept}-d{n}` (diagnostic) or `{concept}-p{n}` (pool). */
  id: string;
  concept: ConceptId;
  /** True for the 16 calibration questions (2/concept); false for pool questions. */
  diagnostic: boolean;
  difficulty: 1 | 2 | 3;
  prompt: string;
  choices: string[];
  correctIndex: number;
  explanation: string;
  misconceptionByChoice: string[];
}

interface QuestionEntry {
  /** Difficulty 1|2|3 (explicit per entry, matching the expansion-file format). */
  d: 1 | 2 | 3;
  /** True for a diagnostic (calibration) question; false for a pool question. */
  diagnostic: boolean;
  q: string;
  c: string[];
  a: number;
  exp: string;
  w: string[];
}

function buildConcept(concept: ConceptId, entries: QuestionEntry[]): Question[] {
  let dCount = 0;
  let pCount = 0;
  return entries.map((entry) => {
    const id = entry.diagnostic
      ? `${concept}-d${(dCount += 1)}`
      : `${concept}-p${(pCount += 1)}`;
    return {
      id,
      concept,
      diagnostic: entry.diagnostic,
      difficulty: entry.d,
      prompt: entry.q,
      choices: entry.c,
      correctIndex: entry.a,
      explanation: entry.exp,
      misconceptionByChoice: entry.w,
    };
  });
}

/**
 * Stamps `diagnostic: false` onto a batch of pool-only entries. The merged
 * expansion questions arrive in `{ d, q, c, a, exp, w }` form (no flag); this
 * asserts, in one auditable place, that every entry it wraps is a pool
 * question — never a per-entry silent default (which HN-09 warns against).
 */
function pool(entries: Omit<QuestionEntry, 'diagnostic'>[]): QuestionEntry[] {
  return entries.map((entry) => ({ ...entry, diagnostic: false }));
}

